'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..','app');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const datajs=fs.readFileSync(path.join(root,'data.js'),'utf8');
const appjs=fs.readFileSync(path.join(root,'app.js'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert(ids.length>15);
assert.equal(new Set(ids).size,ids.length,'duplicate HTML id');
const referenced=[...appjs.matchAll(/byId\('([^']+)'\)/g)].map(m=>m[1]);
for(const id of referenced)assert(ids.includes(id),'missing referenced HTML element: '+id);
let eventHandlers={};
const el=(id)=>({id,value:'',max:'',hidden:false,innerHTML:'',textContent:'',files:[],options:[],attributes:{},className:'',style:{},setAttribute(k,v){this.attributes[k]=v},addEventListener(ev,cb){eventHandlers[id+':'+ev]=cb;},appendChild(ch){(this.children||(this.children=[])).push(ch)},querySelectorAll(){return[];},getScreenCTM(){return null;}});
const elements=Object.fromEntries(ids.map(x=>[x,el(x)]));
elements.nasaMode.value='cevis';
const tabs=['console','science','nasa','method'].map(id=>{const e=el(id);e.dataset={tab:id};return e});
const views=['console','science','nasa','method'].map(id=>elements[id]);
const document={body:{textContent:''},getElementById:id=>elements[id]||null,
 querySelectorAll:s=>s==='.tab'?tabs:s==='.view'?views:[],
 createElement:tag=>el(tag),createElementNS:(ns,tag)=>el(tag)};
const context={window:{},document,console,fetch:async()=>({ok:false,json:async()=>({error:'offline'})}),Number,Math,Array,String};
vm.runInNewContext(datajs,context,{filename:'data.js'});
vm.runInNewContext(appjs,context,{filename:'app.js'});
assert.equal(context.window.PULSAR_DATA.records.length,332);
assert.equal(elements.recordSelect.children.length,19);
assert(elements.timeChart.innerHTML.includes('resline'),'signal plot not produced');
assert(elements.activityRows.innerHTML.includes('run'),'activity table not produced');
assert(elements.nasaAvg.textContent===135,'NASA default not populated');
assert(elements.signalState.innerHTML.includes('REVIEW')||elements.signalState.innerHTML.includes('DISPLAY'));
assert(eventHandlers['reportBtn:click']);
eventHandlers['reportBtn:click']();
assert(elements.report.textContent.includes('CREW SELF-ASSESSMENT'));
assert(elements.report.textContent.includes('NOT MEDICAL ADVICE'));
assert(eventHandlers['nasaMode:change']);
elements.nasaMode.value='t2';eventHandlers['nasaMode:change']();
assert.equal(elements.nasaAvg.textContent,131);
assert(eventHandlers['recordSelect:change']);
elements.recordSelect.value='s1_high_resistance_bike';eventHandlers['recordSelect:change']();
assert(elements.timeChart.innerHTML.includes('rawline'));
console.log('PASS: DOM bindings, 19 recordings, 332 windows, plot, NASA comparison, self-check, record navigation');
